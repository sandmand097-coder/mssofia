import assert from 'node:assert/strict';
import {joinWithBackoff,retryDelayMs,isRetryableJoinError,shouldRecoverDisconnect,delayAbortable} from '../src/components/live-resilience.js';

let passed=0;
const check=(ok,label)=>{assert.ok(ok,label);passed++;console.log('PASS '+label)};
const err=(status,after)=>Object.assign(new Error('synthetic transient error'),{status,retryAfterSeconds:after||0});
check(isRetryableJoinError(err(503))&&isRetryableJoinError(err(429)),'temporary overload and rate limit are retryable');
check(isRetryableJoinError(Object.assign(new TypeError('offline'),{code:'NETWORK_ERROR'})),'offline network failure is retryable');
for(const status of [400,401,403,404,409])check(!isRetryableJoinError(err(status)),'authorization, missing lesson and expired subscriptions must not be retried: '+status);
check(!isRetryableJoinError(Object.assign(Error('cancelled'),{name:'AbortError'})),'aborted join does not retry');
check(retryDelayMs(1,{random:.5})===450&&retryDelayMs(3,{random:.5})===1800,'exponential retry spacing is deterministic in tests');
check(retryDelayMs(1,{retryAfterSeconds:3,random:.5})===3000,'server Retry-After is respected');
check(retryDelayMs(100,{random:1})<=12500,'backoff cannot grow without a bound');
let calls=0,scheduled=[];
const joined=await joinWithBackoff(async()=>{
 calls++;
 if(calls<=2)throw err(503);
 return{token:'synthetic',role:'student'};
},{maxAttempts:4,random:()=>.5,sleep:async()=>{},onRetry:a=>scheduled.push(a)});
check(joined.role==='student'&&calls===3&&scheduled.length===2,'temporary failures heal after two retries');
check(scheduled[0].delayMs<scheduled[1].delayMs,'retry delays spread concurrent viewers');
calls=0;
await assert.rejects(joinWithBackoff(async()=>{calls++;throw err(403)},{sleep:async()=>{}}),/synthetic/);
check(calls===1,'authorization rejection is never hammered by client retries');
calls=0;
await assert.rejects(joinWithBackoff(async()=>{calls++;throw err(503)},{maxAttempts:3,sleep:async()=>{}}),/synthetic/);
check(calls===3,'retry attempts are bounded');
const controller=new AbortController();controller.abort();
await assert.rejects(joinWithBackoff(async()=>{throw Error('should never run')},{signal:controller.signal}),x=>x.name==='AbortError');
check(true,'an aborted route cannot launch a stale token request');
const another=new AbortController();
const sleeping=delayAbortable(120000,another.signal);
another.abort();
await assert.rejects(sleeping,x=>x.name==='AbortError');
check(true,'scheduled recovery wait ends promptly after navigation');
const reasons={CLIENT_INITIATED:1,DUPLICATE_IDENTITY:2,PARTICIPANT_REMOVED:4,ROOM_DELETED:5,JOIN_FAILURE:7,ROOM_CLOSED:10,USER_REJECTED:12};
check(!shouldRecoverDisconnect(4,reasons)&&!shouldRecoverDisconnect(5,reasons),'kicked student or ended lesson cannot auto-rejoin');
check(!shouldRecoverDisconnect(2,reasons),'duplicate login cannot trigger runaway reconnect');
check(shouldRecoverDisconnect(14,reasons)&&shouldRecoverDisconnect(undefined,reasons),'transient connection timeout can trigger controlled recovery');
console.log('RESULT '+passed+' bounded reconnect and transient failure checks passed');
